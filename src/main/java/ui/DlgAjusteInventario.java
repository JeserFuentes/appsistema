private void calcularExistenciaFinal() {
        try {
            int actual = txtExistenciaActual.getText().trim().isEmpty() ? 0 : Integer.parseInt(txtExistenciaActual.getText().trim());
            int ajuste = txtCantidadAjuste.getText().trim().isEmpty() ? 0 : Integer.parseInt(txtCantidadAjuste.getText().trim());
            String tipo = (String) cbxTipoAjuste.getSelectedItem();

            int finalCalc = actual;
            if ("Entrada (+)".equals(tipo)) {
                finalCalc = actual + ajuste;
            } else if ("Salida (-)".equals(tipo)) {
                finalCalc = actual - ajuste;
            }

            txtExistenciaFinal.setText(String.valueOf(finalCalc));
        } catch (NumberFormatException e) {
            txtExistenciaFinal.setText(txtExistenciaActual.getText());
        }
    }
    

