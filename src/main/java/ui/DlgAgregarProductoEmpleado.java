private void calcularCamposItem() {
    try {
        String textoCantidad = txtCantidad.getText().trim();
        String textoPrecio = txtPrecio.getText().trim();
        
        if (!textoCantidad.isEmpty() && !textoPrecio.isEmpty()) {
            double cantidad = Double.parseDouble(textoCantidad);
            double precio = Double.parseDouble(textoPrecio);
            
            double totalLinea = cantidad * precio;
            double subtotal = totalLinea / 1.12;
            double iva = totalLinea - subtotal;
            
            txtSubtotal.setText(String.format("%.2f", subtotal));
            txtIva.setText(String.format("%.2f", iva));
            txtTotalLinea.setText(String.format("%.2f", totalLinea));
        } else {
            txtSubtotal.setText("0.00");
            txtIva.setText("0.00");
            txtTotalLinea.setText("0.00");
        }
    } catch (NumberFormatException e) {
        txtSubtotal.setText("0.00");
        txtIva.setText("0.00");
        txtTotalLinea.setText("0.00");
    }

}
